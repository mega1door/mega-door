/**
 * نوع بيانات موديل الباب - يطابق الحقول المطلوبة في مواصفات المشروع:
 * نوع الموديل، رقم الموديل، عدة صور، النوع، اللون، القياسات، المواصفات، أين يمكن استخدامه.
 */

/** معرّف القسم - يطابق id أحد الأقسام المُدارة من لوحة الإدارة (انظر src/lib/categoriesStore.ts).
 * لم يعد Union ثابت بالأقسام الثلاثة الافتراضية حتى يمكن إضافة أقسام جديدة من لوحة الإدارة
 * دون تعديل الكود. */
export type DoorCategory = string;

export interface DoorModel {
  /** معرّف فريد يستخدم في الرابط: /model/:id */
  id: string;
  /** كود الموديل كما يظهر للزبون، مثال: MD-101 */
  modelNumber: string;
  /** اسم الموديل التسويقي */
  name: string;
  /** القسم: داخلية / خارجية / قواطع داخلية */
  category: DoorCategory;
  /** نوع/خامة الباب: خشب، حديد، MDF، ستيل... - اختياري: يُترك فارغاً إن لم يكن مؤكداً، ولا يُعرض حينها بالواجهة */
  material?: string;
  /** اللون أو الألوان المتوفرة - اختياري: يُترك فارغاً إن لم يكن مؤكداً */
  color?: string;
  /** Supabase models.color_code; keep as text to retain leading zeros. */
  colorCode?: string;
  /** القياسات، مثال: 100 × 210 سم - اختياري: يُترك فارغاً إن لم يكن مؤكداً */
  dimensions?: string;
  /** نقاط المواصفات التقنية - اختياري: تُترك فارغة إن لم تكن مؤكدة */
  specs?: string[];
  /** أين يمكن استخدام هذا الموديل - اختياري: يُترك فارغاً إن لم يكن مؤكداً */
  usage?: string;
  /** روابط الصور - الصورة الأولى هي الصورة الرئيسية */
  images: string[];
  /** يظهر ضمن قسم "الأكثر طلباً" - بدون أي قيد على العدد، يتحكم بيه فريق ميكا بالكامل لكل موديل */
  isPopular: boolean;
  /** لون مميز (hex) كان يُستخدم سابقاً لتلوين مشهد الباب التوضيحي (DoorScene) قبل استبداله
   * بصور حقيقية بكل مكان - غير مستخدم حالياً بأي واجهة، اختياري ويمكن تجاهله بالكامل. */
  accent?: string;
  /** وصف قصير لطابع التصميم، يظهر كتسمية تحت رقم الموديل ببطاقة سلايدر "الأكثر طلباً" -
   * اختياري: إذا ما تُرك فارغاً ما تظهر هذي التسمية إطلاقاً. */
  styleLabel?: string;
  /** السعر - حقل داخلي بلوحة الإدارة فقط حالياً، غير معروض بأي صفحة عامة بالموقع. */
  price?: number;
}
